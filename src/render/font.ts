const BITMAPS = new Map<string, boolean[][]>(
  Object.entries(GLYPHS).map(([ch, s]) => [ch, s.split("|").map((row) => [...row].map((c) => c === "#"))]),
);

export const GLYPH_W = 5;
export const GLYPH_H = 7;

export function glyph(ch: string): boolean[][] {
  return BITMAPS.get(ch.toUpperCase()) ?? BITMAPS.get("?")!;
}

export function textWidth(text: string, scale = 1): number {
  return text.length ? (text.length * (GLYPH_W + 1) - 1) * scale : 0;
}
